import base64, json, subprocess, os, sys, tempfile
# usage: python3 mkfonts.py <path-to-app-repo>   (writes <repo>/js/pdf-fonts.js)
APP=sys.argv[1] if len(sys.argv)>1 else '.'
TMP=tempfile.mkdtemp()
from fontTools.ttLib import TTFont
D='/usr/share/fonts/truetype/dejavu/'
fonts={'r':'DejaVuSerifCondensed.ttf','b':'DejaVuSerifCondensed-Bold.ttf','i':'DejaVuSerifCondensed-Italic.ttf','h':'DejaVuSansCondensed-Bold.ttf','s':'DejaVuSansCondensed.ttf'}
uni='U+0020-007E,U+00A0-00FF,U+0100-017F,U+0370-03FF,U+2010-2027,U+2030-2044,U+2070-209F,U+20AC,U+2190-21FF,U+2212,U+2213,U+2215,U+2217,U+2248,U+2260,U+2264,U+2265,U+25B2,U+25BC,U+2713,U+2022'
out={}
for k,f in fonts.items():
    tmp=os.path.join(TMP,'%s.ttf'%k)
    subprocess.check_call(['pyftsubset',D+f,'--unicodes='+uni,'--layout-features=','--no-hinting','--desubroutinize','--output-file='+tmp,'--drop-tables+=GSUB,GPOS,kern'])
    t=TTFont(tmp); cmap=t.getBestCmap(); hm=t['hmtx']; upm=t['head'].unitsPerEm
    m={}
    for cp,g in cmap.items():
        m[cp]=[t.getGlyphID(g), round(hm[g][0]*1000/upm)]
    asc=round(t['hhea'].ascent*1000/upm); desc=round(t['hhea'].descent*1000/upm)
    bb=t['head']; 
    out[k]={'ttf':base64.b64encode(open(tmp,'rb').read()).decode(),'map':{str(a):b for a,b in m.items()},'asc':asc,'desc':desc,'bbox':[round(bb.xMin*1000/upm),round(bb.yMin*1000/upm),round(bb.xMax*1000/upm),round(bb.yMax*1000/upm)],'n':t['maxp'].numGlyphs,'size':os.path.getsize(tmp)}
    print(k,os.path.getsize(tmp),len(m))
open(os.path.join(APP,'js','pdf-fonts.js'),'w').write('/* Subset DejaVu Condensed fonts (free license) embedded for the PDF generator. Generated by tools/mkfonts.py */\nwindow.SP_PDF_FONTS='+json.dumps(out,separators=(',',':'))+';\n')
