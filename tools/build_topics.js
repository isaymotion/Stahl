// Builds ../stahl/data/topics.js from work/r2/topics_vocab.json + work/r2/topic_map.json.
// Usage: node tools/build_topics.js ../stahl
const fs = require('fs'), path = require('path');
const app = process.argv[2] || '../stahl';
const vocab = JSON.parse(fs.readFileSync(path.join(__dirname, '../work/r2/topics_vocab.json'), 'utf8'));
const map = JSON.parse(fs.readFileSync(path.join(__dirname, '../work/r2/topic_map.json'), 'utf8'));
const ids = new Set(vocab.map(v => v.id));
const bad = Object.entries(map).filter(([k, v]) => !ids.has(v));
if (bad.length) { console.error('unknown topic ids', bad.slice(0, 5)); process.exit(1); }
const keys = Object.keys(map).sort();
let out = '/* Cross-chapter topics (24.0.0). Every card and board question ("chNN/deck/id") belongs to one topic.\n' +
  '   Generated by dev-tools/tools/build_topics.js from work/r2/topics_vocab.json and topic_map.json; edit those, then rebuild. */\n';
out += 'SP.topics = [\n' + vocab.map(v => '  ' + JSON.stringify({ id: v.id, label: v.label, group: v.group, scope: v.scope })).join(',\n') + '\n];\n';
out += 'SP.topicMap = {\n' + keys.map(k => '  ' + JSON.stringify(k) + ':' + JSON.stringify(map[k])).join(',\n') + '\n};\n';
fs.writeFileSync(path.join(app, 'data/topics.js'), out);
console.log('topics', vocab.length, 'items', keys.length, 'bytes', out.length);
